import {
  createAcademicExercise,
  multiNumberInteraction,
  numberInteraction,
  singleChoiceInteraction,
} from "../exercise-builder.js";

const solution = (...texts) => texts.map((text, index) => ({
  step: index + 1,
  title: ["Principio", "Representación", "Cálculo", "Interpretación"][index] ?? `Paso ${index + 1}`,
  text,
}));
const choice = (options, correct) => singleChoiceInteraction(
  options.map((content, index) => [String.fromCharCode(97 + index), content]),
  String.fromCharCode(97 + correct)
);
const base = (exercise) => createAcademicExercise({
  prerequisites: [],
  objectives: [exercise.objective],
  estimatedMinutes: exercise.estimatedMinutes ?? 5,
  ...exercise,
  objective: undefined,
  bonusEligible: false,
}, { unit: 2 });
const conceptual = (data) => base({
  ...data,
  type: data.type ?? "conceptual",
  representation: data.representation ?? "verbal",
  cognitiveLevel: data.cognitiveLevel ?? "understand",
  answer: { kind: "text", value: data.answer },
  interaction: choice(data.options, data.correct),
  hints: data.hints ?? [data.hint],
  solution: solution(...data.solution),
  options: undefined, correct: undefined, hint: undefined, answerText: undefined,
});
const numerical = (data) => base({
  ...data,
  type: data.type ?? "numerical",
  representation: data.representation ?? "numerical",
  cognitiveLevel: data.cognitiveLevel ?? "apply",
  answer: { kind: "number", value: data.value, display: data.display },
  tolerance: data.tolerance ?? 0.01,
  expectedUnit: data.unit,
  interaction: numberInteraction(data.field, data.unit),
  hints: data.hints ?? [data.hint],
  solution: solution(...data.solution),
  value: undefined, display: undefined, unit: undefined, field: undefined, hint: undefined,
});
const values = (data) => base({
  ...data,
  type: data.type ?? "numerical",
  representation: data.representation ?? "vectorial",
  cognitiveLevel: data.cognitiveLevel ?? "apply",
  answer: { kind: "values", values: data.values.map(([symbol, value, unit]) => ({ symbol, value, unit })) },
  tolerance: data.tolerance ?? 0.01,
  expectedUnit: data.expectedUnit,
  interaction: multiNumberInteraction(data.fields),
  hints: data.hints ?? [data.hint],
  solution: solution(...data.solution),
  values: undefined, fields: undefined, hint: undefined,
});

